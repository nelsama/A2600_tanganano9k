"""menu.bin (10 KB) -> menu_l.hex (2 KB at $D800), menu.hex (8 KB at $E000), menu_cfg.vh"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
d = open(sys.argv[1], 'rb').read()
assert len(d) == 10240
def w(p, s):
    with open(os.path.join(here, p), 'w', newline='\n') as f: f.write(s)
h = lambda x: ''.join('%02x\n' % y for y in x)
w('menu_l.hex', h(d[:2048]))
w('menu.hex', h(d[2048:]))
p = here.replace('\\', '/')
w('../src/sd/menu_cfg.vh', '// generated by menu/build.sh\n`define MENU_HEX "%s/menu.hex"\n`define MENU_HEX_L "%s/menu_l.hex"\n' % (p, p))
